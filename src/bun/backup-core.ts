export interface BackupPublicationReceipt {
  operationId: string;
  targetPath: string;
  sha256: string;
  bytes: number;
  pid: number;
  publishedAt: number;
}

const RECEIPT_OP_ID_RE = /^[a-zA-Z0-9_-]{1,128}$/;

function resolveBackupReceiptPath(operationId: string): string | null {
  if (!operationId || !RECEIPT_OP_ID_RE.test(operationId)) return null;
  return path.join(tmpdir(), `.fo-pub-receipt-${operationId}.json`);
}

export interface PublicationReceiptWriteOptions {
  /** Test seam: override the file fsync call. */
  fsync?: (fd: number) => void;
  /** Test seam: override the containing-directory fsync call. */
  syncDirectory?: (dirPath: string) => void;
}

function receiptErrorCode(
  err: unknown,
): "RECEIPT_EXISTS" | "RECEIPT_UNWRITABLE" | "RECEIPT_IO_ERROR" {
  const code = (err as { code?: string } | undefined)?.code;
  if (code === "EEXIST") return "RECEIPT_EXISTS";
  if (
    code === "EACCES" ||
    code === "EPERM" ||
    code === "EROFS" ||
    code === "ENOENT" ||
    code === "ENOTDIR" ||
    code === "ENOSPC"
  ) {
    return "RECEIPT_UNWRITABLE";
  }
  return "RECEIPT_IO_ERROR";
}

/**
 * Writes the auxiliary publication receipt with exclusive-create semantics.
 *
 * Contract (R8B):
 * - Never overwrites an existing receipt (`O_EXCL`), never follows symlinks (`O_NOFOLLOW`).
 * - Validates the operation ID, target path, SHA-256 and byte count before writing.
 * - `fsync`s the file (so the content is durable) and the directory (so the entry is durable).
 * - Returns a structured failure instead of silently swallowing errors: the caller must be
 *   able to distinguish "no receipt could be written" from "this operation did not publish".
 */
export function writeBackupPublicationReceipt(
  receipt: BackupPublicationReceipt,
  options?: PublicationReceiptWriteOptions,
): PublicationReceiptWriteOutcome {
  const receiptPath = resolveBackupReceiptPath(receipt?.operationId);
  if (!receiptPath) {
    return {
      ok: false,
      path: null,
      code: "RECEIPT_PATH_INVALID",
      message: `Invalid publication receipt operation ID: ${String(receipt?.operationId)}`,
    };
  }
  if (
    typeof receipt.targetPath !== "string" ||
    receipt.targetPath.trim().length === 0 ||
    !path.isAbsolute(receipt.targetPath) ||
    typeof receipt.sha256 !== "string" ||
    !/^[0-9a-f]{64}$/.test(receipt.sha256) ||
    typeof receipt.bytes !== "number" ||
    !Number.isInteger(receipt.bytes) ||
    receipt.bytes <= 0 ||
    typeof receipt.pid !== "number" ||
    !Number.isInteger(receipt.pid) ||
    receipt.pid <= 0
  ) {
    return {
      ok: false,
      path: receiptPath,
      code: "RECEIPT_PATH_INVALID",
      message: "Publication receipt fields failed validation",
    };
  }

  let created = false;
  let fd: number | null = null;
  try {
    const flags =
      constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | ((constants as any).O_NOFOLLOW ?? 0);
    fd = openSync(receiptPath, flags, 0o600);
    created = true;
    const buf = Buffer.from(JSON.stringify(receipt));
    writeSync(fd, buf);
    (options?.fsync ?? fsyncSync)(fd);
  } catch (err) {
    if (fd !== null) {
      try {
        closeSync(fd);
      } catch {
        /* best effort */
      }
      fd = null;
    }
    // A failed write must not leave a partial receipt that could later be mistaken
    // for authoritative evidence. Preserve any pre-existing (colliding) file.
    if (created) {
      try {
        unlinkSync(receiptPath);
      } catch {
        /* best effort */
      }
    }
    return {
      ok: false,
      path: receiptPath,
      code: receiptErrorCode(err),
      message: (err as Error)?.message ?? String(err),
    };
  } finally {
    if (fd !== null) {
      try {
        closeSync(fd);
      } catch {
        /* best effort */
      }
    }
  }

  let directorySynced = true;
  try {
    (options?.syncDirectory ?? syncDirectory)(path.dirname(receiptPath));
  } catch {
    // The receipt file itself is valid and readable; only its crash-durability is
    // weaker. Report that explicitly rather than discarding the evidence.
    directorySynced = false;
  }

  return { ok: true, path: receiptPath, directorySynced };
}

export function readBackupPublicationReceipt(operationId: string): BackupPublicationReceipt | null {
  const receiptPath = resolveBackupReceiptPath(operationId);
  if (!receiptPath) return null;
  try {
    const st = lstatSync(receiptPath);
    if (st.isSymbolicLink() || !st.isFile() || st.size <= 0 || st.size > 16384) {
      return null;
    }
    const parsed = JSON.parse(readFileSync(receiptPath, "utf8")) as BackupPublicationReceipt;
    if (
      !parsed ||
      typeof parsed !== "object" ||
      parsed.operationId !== operationId ||
      typeof parsed.targetPath !== "string" ||
      typeof parsed.sha256 !== "string" ||
      !/^[0-9a-f]{64}$/.test(parsed.sha256) ||
      typeof parsed.bytes !== "number" ||
      !Number.isInteger(parsed.bytes) ||
      parsed.bytes <= 0
    ) {
      return null;
    }
    return parsed;
  } catch {
    return null;
  }
}

export function removeBackupPublicationReceipt(operationId: string): void {
  const receiptPath = resolveBackupReceiptPath(operationId);
  if (!receiptPath) return;
  try {
    unlinkSync(receiptPath);
  } catch {
    /* best effort */
  }
}

export function cleanStalePublicationReceipts(
  maxAgeMs = 3600_000,
  options?: { preserveUnreconciledPublished?: boolean },
): { cleaned: string[]; preserved: string[] } {
  const result = { cleaned: [] as string[], preserved: [] as string[] };
  const tmp = tmpdir();
  let entries: string[];
  try {
    entries = readdirSync(tmp);
  } catch {
    return result;
  }
  const RECEIPT_SCAN_RE = /^\.fo-pub-receipt-([a-zA-Z0-9_-]+)\.json$/;
  const now = Date.now();
  const preservePublished = options?.preserveUnreconciledPublished !== false;

  for (const entry of entries) {
    const match = RECEIPT_SCAN_RE.exec(entry);
    if (!match || !match[1]) continue;
    const opId = match[1];
    const filePath = path.join(tmp, entry);
    try {
      const receipt = readBackupPublicationReceipt(opId);
      if (!receipt) {
        const st = lstatSync(filePath);
        if (now - st.mtimeMs > maxAgeMs) {
          unlinkSync(filePath);
          result.cleaned.push(filePath);
        } else {
          result.preserved.push(filePath);
        }
        continue;
      }
      if (isPidAlive(receipt.pid)) {
        result.preserved.push(filePath);
        continue;
      }
      // If destination artifact still exists on disk, preserve receipt as evidence for publication reconciliation!
      if (preservePublished && pathExistsOrSymlink(receipt.targetPath)) {
        result.preserved.push(filePath);
        continue;
      }
      if (now - receipt.publishedAt >= maxAgeMs) {
        unlinkSync(filePath);
        result.cleaned.push(filePath);
      } else {
        result.preserved.push(filePath);
      }
    } catch {
      result.preserved.push(filePath);
    }
  }
  return result;
}


