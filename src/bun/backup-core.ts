export const STAGING_METADATA_FILENAME = ".forgeorbit-ownership.json";
export const STAGING_LOCK_FILENAME = ".lock";
/** Structured recovery summary written into a restored profile before publication. */
export const RESTORE_RECOVERY_FILENAME = ".forgeorbit-recovery.json";
/**
 * Post-publication confirmation marker (FO-P2-005-A). Written only after the
 * restored directory and its database digest have been verified at their final
 * location, so activation can distinguish a confirmed restore from a merely
 * published (PUBLISHED_UNCONFIRMED / INDETERMINATE) one.
 */
export const RESTORE_CONFIRMATION_FILENAME = ".forgeorbit-restore-confirmed.json";

/** Write ownership metadata file inside a staging directory. */
export function writeStagingOwnershipMetadata(
  stagingDir: string,
  metadata: StagingOwnershipMetadata,
  sync = true,
): void {
  const metadataPath = path.join(stagingDir, STAGING_METADATA_FILENAME);
  const payload = JSON.stringify(metadata, null, 2);
  writeFileSync(metadataPath, payload, { mode: 0o600 });
  if (sync) {
    try {
      syncFile(metadataPath);
    } catch {
      /* best effort sync of metadata */
    }
  }
}

/** Read ownership metadata from a staging directory. Returns null if missing, corrupt, or unparseable. */
export function readStagingOwnershipMetadata(
  stagingDir: string,
): StagingOwnershipMetadata | null {
  const metadataPath = path.join(stagingDir, STAGING_METADATA_FILENAME);
  try {
    const st = lstatSync(metadataPath);
    if (st.isSymbolicLink() || !st.isFile()) return null;
    const raw = readFileSync(metadataPath, "utf8");
    const parsed = JSON.parse(raw);
    if (
      !parsed ||
      typeof parsed !== "object" ||
      parsed.version !== 1 ||
      typeof parsed.subsystem !== "string" ||
      typeof parsed.operationId !== "string" ||
      (parsed.runnerOperationId !== undefined && typeof parsed.runnerOperationId !== "string") ||
      typeof parsed.pid !== "number" ||
      typeof parsed.createdAt !== "number" ||
      typeof parsed.state !== "string"
    ) {
      return null;
    }
    return parsed as StagingOwnershipMetadata;
  } catch {
    return null;
  }
}

/**
 * Non-overlapping namespace regexes for staging directories:
 * - Backup Core: `.fo-core.`
 * - Backup Manager: `.fo-snapshot.`
 * - Backup Restore: `.fo-restore.`
 */
export const CORE_STAGING_DIR_RE = /^\..+\.fo-core\.[0-9a-f-]{36}\.tmp$/i;
export const SNAPSHOT_STAGING_DIR_RE = /^\..+\.fo-snapshot\.[0-9a-f-]{36}\.tmp$/i;
export const RESTORE_STAGING_DIR_RE = /^\..+\.fo-restore\.[0-9a-f-]{36}\.tmp$/i;

/** Scanning regexes supporting both current and historical candidate directory names. */
export const CORE_STAGING_SCAN_RE = /^\.(?:.+fo-core\.|.+core\.|database\.|fo-core-pub-tmp-)[0-9a-f-]{36}\.(?:tmp|sqlite)$/i;
export const SNAPSHOT_STAGING_SCAN_RE = /^\.(?:.+fo-snapshot\.|.+snapshot\.|forgeorbit-snapshot\.)[0-9a-f-]{36}\.tmp$/i;
export const RESTORE_STAGING_SCAN_RE = /^\.(?:.+fo-restore\.|.+restore\.)[0-9a-f-]{36}\.tmp$/i;

/**
 * Safely scan a directory and clean up abandoned staging directories owned exclusively by `subsystem`.
 *
 * Safety Invariants:
 * 1. Checks that `directory` itself is not a symbolic link.
 * 2. Only considers entries matching `scanRegex` for that subsystem.
 * 3. Never follows or unlinks symbolic links or special files.
 * 4. Fails closed (preserves) any directory missing valid `.forgeorbit-ownership.json`.
 * 5. Fails closed (preserves) any directory owned by a different subsystem.
 * 6. Never deletes active staging operations (detected via held advisory flock).
 * 7. Never deletes operations where the creating process is still alive.
 * 8. Only removes directories when advisory lock is free AND creating PID is dead (ESRCH).
 */
export function cleanSubsystemStaging(
  directory: string,
  subsystem: StagingSubsystem,
  scanRegex: RegExp,
): { cleaned: string[]; errors: string[] } {
  const cleaned: string[] = [];
  const errors: string[] = [];
  const resolved = path.resolve(directory);

  if (!pathExistsOrSymlink(resolved)) return { cleaned, errors };

  try {
    const st = lstatSync(resolved);
    if (st.isSymbolicLink()) {
      errors.push(`Directory is a symbolic link: ${resolved}`);
      return { cleaned, errors };
    }
    if (!st.isDirectory()) {
      errors.push(`Path is not a directory: ${resolved}`);
      return { cleaned, errors };
    }
  } catch (err) {
    errors.push(`Failed to stat directory ${resolved}: ${(err as Error).message}`);
    return { cleaned, errors };
  }

  let entries: string[];
  try {
    entries = readdirSync(resolved);
  } catch (err) {
    errors.push(`Failed to read directory ${resolved}: ${(err as Error).message}`);
    return { cleaned, errors };
  }

  for (const entry of entries) {
    if (!scanRegex.test(entry)) continue;
    const full = path.join(resolved, entry);
    let st: ReturnType<typeof lstatSync>;
    try {
      st = lstatSync(full);
    } catch (err) {
      errors.push(`Failed to stat ${full}: ${(err as Error).message}`);
      continue;
    }

    // Never follow or remove symbolic links or non-directories (fail closed on unsafe objects)
    if (st.isSymbolicLink()) {
      errors.push(`Untrusted symbolic link in staging location: ${full}`);
      continue;
    }
    if (!st.isDirectory()) {
      // Loose temporary files without ownership metadata: fail closed, do not delete
      continue;
    }

    // Validate ownership metadata
    const metadata = readStagingOwnershipMetadata(full);
    if (!metadata) {
      // Missing or malformed ownership metadata -> fail closed, do not delete!
      continue;
    }

    // Cross-subsystem isolation check
    if (metadata.subsystem !== subsystem) {
      // Owned by another subsystem -> do not delete!
      continue;
    }

    // Check locking evidence and process liveness
    const lockPath = path.join(full, STAGING_LOCK_FILENAME);
    let lockFd: number | null = null;
    let lockAcquired = false;
    try {
      lockFd = openSync(lockPath, constants.O_RDWR | constants.O_CREAT, 0o600);
      lockAcquired = tryAcquireFlock(lockFd);
    } catch {
      lockAcquired = false;
    }

    try {
      if (!lockAcquired) {
        // Lock is held by an active operation! Active operations MUST NOT be deleted.
        continue;
      }

      // Lock is free, now verify that the creating process is actually dead
      const pidAlive = isPidAlive(metadata.pid);
      if (pidAlive) {
        // Creating PID is still alive (or reused) -> fail closed!
        continue;
      }

      // Verified dead abandoned staging directory: safe to remove
      try {
        rmSync(full, { recursive: true, force: true });
        cleaned.push(full);
      } catch (err) {
        errors.push(`Failed to remove stale staging directory ${full}: ${(err as Error).message}`);
      }
    } finally {
      if (lockFd !== null) {
        try {
          closeSync(lockFd);
        } catch {
          /* ignore */
        }
      }
    }
  }

  return { cleaned, errors };
}

export interface ScopedWorkerCleanupOptions {
  /** The parent directory containing the expected staging directory. */
  parentDir: string;
  /** Subsystem: 'backup-core' | 'backup-manager' | 'backup-restore'. */
  subsystem: StagingSubsystem;
  /** Expected target path (e.g. backup file path, snapshot directory path). */
  targetPath: string;
  /** Runner operation ID to match against metadata.runnerOperationId. */
  runnerOperationId?: string;
  /** Terminated worker process PID to match against metadata.pid. */
  workerPid?: number;
  /** Optional staging directory path reported by the worker to check as a candidate. */
  candidateStagingDir?: string;
}

export interface ScopedCleanupResult {
  attempted: boolean;
  cleaned: string[];
  preserved: Array<{ path: string; reason: string }>;
  errors: string[];
}

/**
 * Narrowly scoped, fail-closed cleanup for an abandoned staging directory owned by a terminated worker.
 *
 * Requirements:
 * 1. Validates canonical path containment (strictly within parentDir).
 * 2. Rejects any symlinks without following or removing them.
 * 3. Enforces namespace regex matching for the subsystem.
 * 4. Fails closed on missing, malformed, or corrupt metadata.
 * 5. Strictly matches subsystem, targetPath, workerPid, and runnerOperationId.
 * 6. Checks flock: preserves active operations when lock is held.
 * 7. Checks PID liveness: preserves staging if PID is alive or reused.
 * 8. Never deletes published or completed artifacts.
 */
export function cleanScopedWorkerStaging(
  options: ScopedWorkerCleanupOptions,
): ScopedCleanupResult {
  const result: ScopedCleanupResult = {
    attempted: true,
    cleaned: [],
    preserved: [],
    errors: [],
  };

  const resolvedParent = path.resolve(options.parentDir);
  if (!pathExistsOrSymlink(resolvedParent)) {
    return result;
  }

  try {
    const parentSt = lstatSync(resolvedParent);
    if (parentSt.isSymbolicLink() || !parentSt.isDirectory()) {
      result.errors.push(`Parent path is not a regular directory: ${resolvedParent}`);
      return result;
    }
  } catch (err) {
    result.errors.push(`Failed to stat parent directory ${resolvedParent}: ${(err as Error).message}`);
    return result;
  }

  let scanRegex: RegExp;
  switch (options.subsystem) {
    case "backup-core":
      scanRegex = CORE_STAGING_SCAN_RE;
      break;
    case "backup-manager":
      scanRegex = SNAPSHOT_STAGING_SCAN_RE;
      break;
    case "backup-restore":
      scanRegex = RESTORE_STAGING_SCAN_RE;
      break;
    default:
      result.errors.push(`Unknown staging subsystem: ${String(options.subsystem)}`);
      return result;
  }

  const candidatePaths = new Set<string>();

  // 1. Evaluate candidate reported by worker (if any)
  if (options.candidateStagingDir) {
    const resolvedCandidate = path.resolve(options.candidateStagingDir);
    const parentOfCandidate = path.dirname(resolvedCandidate);
    if (parentOfCandidate === resolvedParent && !path.relative(resolvedParent, resolvedCandidate).includes("..")) {
      candidatePaths.add(resolvedCandidate);
    } else {
      result.preserved.push({
        path: resolvedCandidate,
        reason: "CANONICAL_PATH_CONTAINMENT_VIOLATION",
      });
      result.errors.push(`Candidate staging path escaped parent directory: ${resolvedCandidate}`);
    }
  }

  // 2. Scan parent directory for matching subsystem staging entries
  try {
    const entries = readdirSync(resolvedParent);
    for (const entry of entries) {
      if (scanRegex.test(entry)) {
        candidatePaths.add(path.join(resolvedParent, entry));
      }
    }
  } catch (err) {
    result.errors.push(`Failed to read parent directory ${resolvedParent}: ${(err as Error).message}`);
    return result;
  }

  const expectedTargetPath = path.resolve(options.targetPath);

  for (const candidate of candidatePaths) {
    let st: ReturnType<typeof lstatSync>;
    try {
      st = lstatSync(candidate);
    } catch {
      continue;
    }

    if (st.isSymbolicLink()) {
      result.preserved.push({ path: candidate, reason: "UNTRUSTED_SYMLINK" });
      result.errors.push(`Untrusted symbolic link in staging location: ${candidate}`);
      continue;
    }
    if (!st.isDirectory()) {
      result.preserved.push({ path: candidate, reason: "NOT_A_DIRECTORY" });
      continue;
    }

    const baseName = path.basename(candidate);
    if (!scanRegex.test(baseName)) {
      result.preserved.push({ path: candidate, reason: "NAMESPACE_MISMATCH" });
      continue;
    }

    // Ownership metadata verification
    const metadata = readStagingOwnershipMetadata(candidate);
    if (!metadata) {
      result.preserved.push({ path: candidate, reason: "MISSING_OR_CORRUPT_METADATA" });
      continue;
    }

    if (metadata.subsystem !== options.subsystem) {
      result.preserved.push({ path: candidate, reason: "SUBSYSTEM_MISMATCH" });
      continue;
    }

    const metaTarget = path.resolve(metadata.targetPath ?? "");
    const targetMatches =
      metaTarget === expectedTargetPath ||
      (options.subsystem === "backup-manager" && path.dirname(metaTarget) === expectedTargetPath);

    if (!targetMatches) {
      result.preserved.push({ path: candidate, reason: "TARGET_PATH_MISMATCH" });
      continue;
    }

    if (options.workerPid !== undefined && metadata.pid !== options.workerPid) {
      result.preserved.push({ path: candidate, reason: "PID_MISMATCH" });
      continue;
    }

    if (
      options.runnerOperationId &&
      metadata.runnerOperationId &&
      metadata.runnerOperationId !== options.runnerOperationId
    ) {
      result.preserved.push({ path: candidate, reason: "OPERATION_ID_MISMATCH" });
      continue;
    }

    // Never delete published or completed staging
    if (metadata.state === "completed") {
      result.preserved.push({ path: candidate, reason: "ALREADY_PUBLISHED" });
      continue;
    }

    // Advisory flock verification: check if an active process still holds the lock
    const lockPath = path.join(candidate, STAGING_LOCK_FILENAME);
    let lockFd: number | null = null;
    let lockAcquired = false;
    try {
      lockFd = openSync(lockPath, constants.O_RDWR | constants.O_CREAT, 0o600);
      lockAcquired = tryAcquireFlock(lockFd);
    } catch {
      lockAcquired = false;
    }

    try {
      if (!lockAcquired) {
        result.preserved.push({ path: candidate, reason: "ACTIVE_LOCK_HELD" });
        continue;
      }

      // Check PID liveness
      if (isPidAlive(metadata.pid)) {
        result.preserved.push({ path: candidate, reason: "PID_ALIVE" });
        continue;
      }

      // Safe to delete abandoned staging directory
      try {
        rmSync(candidate, { recursive: true, force: true });
        result.cleaned.push(candidate);
      } catch (rmErr) {
        result.errors.push(`Failed to remove staging directory ${candidate}: ${(rmErr as Error).message}`);
      }
    } finally {
      if (lockFd !== null) {
        try {
          closeSync(lockFd);
        } catch {
          /* ignore */
        }
      }
    }
  }

  // When cleaning backup-core staging, also recover any stale publication temp files (.tmp/.lock/.meta.json)
  if (options.subsystem === "backup-core") {
    const pubTempResult = recoverStalePublicationTempFiles(resolvedParent);
    result.cleaned.push(...pubTempResult.cleaned);
    result.preserved.push(...pubTempResult.preserved);
    result.errors.push(...pubTempResult.errors);
  }

  return result;
}

/**
 * Atomically publishes a staging directory to its final destination using
 * exclusive no-replace semantics. Refuses to overwrite an existing directory
 * (even if empty) or file.
 */
export function publishDirectoryExclusive(
  stagingDir: string,
  destinationDir: string,
): void {
  const resolvedStaging = path.resolve(stagingDir);
  const resolvedDest = path.resolve(destinationDir);

  // Fast pre-check: fail immediately if destination already exists or is a symlink
  if (pathExistsOrSymlink(resolvedDest)) {
    const err = new Error(`Destination directory already exists: ${resolvedDest}`);
    (err as { code?: string }).code = "EEXIST";
    throw err;
  }

  // On macOS, invoke Darwin renamex_np with RENAME_EXCL for kernel-level atomic no-replace publication
  const renamex = getDarwinRenamex();
  if (renamex) {
    const errno = renamex(resolvedStaging, resolvedDest);
    if (errno === 0) {
      return; // Atomic exclusive publication succeeded
    }
    if (errno === 17 /* EEXIST */) {
      const err = new Error(`Destination directory already exists: ${resolvedDest}`);
      (err as { code?: string }).code = "EEXIST";
      throw err;
    }
    const err = new Error(`Atomic exclusive directory rename failed (errno ${errno})`);
    (err as { code?: string }).code = errno === 18 ? "EXDEV" : "IO_ERROR";
    throw err;
  }

  // If running on non-Darwin platforms where renamex_np is unavailable:
  // Refuse to fall back to an unsafe POSIX renameSync that silently replaces empty directories.
  throw new Error(
    `Atomic exclusive directory publication is unsupported on platform '${process.platform}' without native no-replace primitives.`,
  );
}

/**
 * Atomically and exclusively publishes a file backup to destinationPath.
 *
 * Guarantees:
 * 1. Crash-safety: never leaves a partially written file at destinationPath if process crashes or power is lost.
 * 2. Exclusive: fails closed if destinationPath exists or is a symlink (EEXIST / TARGET_EXISTS).
 * 3. Fallback: when hard links fail (e.g. EXDEV, ENOTSUP), stages the copy in a private temporary file
 *    on the destination filesystem (.fo-core-pub-tmp-*.tmp), fsyncs it, and publishes atomically via link
 *    or Darwin renamex_np with RENAME_EXCL.
 * 4. Fails closed with UNSUPPORTED_FILESYSTEM if no atomic exclusive publication primitive is supported.
 */
export function publishFileExclusive(
  sourceFile: string,
  destinationPath: string,
  options: {
    fs?: {
      link?: (src: string, dst: string) => void;
      unlink?: (p: string) => void;
      copyFile?: (src: string, dst: string, mode?: number) => void;
    };
    syncFileFn?: (p: string) => void;
    syncDirFn?: (p: string) => void;
    expectedSha256?: string;
  } = {},
): void {
  const resolvedDest = path.resolve(destinationPath);
  const parentDir = path.dirname(resolvedDest);
  const linkFn = options.fs?.link ?? linkSync;
  const unlinkFn = options.fs?.unlink ?? unlinkSync;
  const copyFileFn = options.fs?.copyFile ?? copyFileSync;
  const syncFileFn = options.syncFileFn ?? syncFile;
  const syncDirFn = options.syncDirFn ?? syncDirectory;

  // 1. Destination pre-check: fail closed if destination already exists or is a symlink
  if (pathExistsOrSymlink(resolvedDest)) {
    throw new BackupCoreError(
      `Destination path already exists: ${resolvedDest}`,
      "TARGET_EXISTS",
    );
  }

  // 2. Primary strategy: hard link (atomic, exclusive, no-replace)
  let linkErrCode: string | undefined;
  try {
    linkFn(sourceFile, resolvedDest);
    try {
      unlinkFn(sourceFile);
    } catch {
      /* best effort */
    }
    try {
      syncDirFn(parentDir);
    } catch (syncErr) {
      throw new BackupCoreError(
        `Publication succeeded at destination but directory synchronization failed: ${(syncErr as Error).message}`,
        "IO_ERROR",
        syncErr,
      );
    }
    return;
  } catch (linkErr: unknown) {
    if (linkErr instanceof BackupCoreError) throw linkErr;
    linkErrCode = (linkErr as { code?: string })?.code;
    if (linkErrCode === "EEXIST" || pathExistsOrSymlink(resolvedDest)) {
      throw new BackupCoreError(
        `Destination path already exists: ${resolvedDest}`,
        "TARGET_EXISTS",
      );
    }
  }

  // 3. Crash-atomic fallback: stage into private temporary file on destination filesystem
  const pubId = randomUUID();
  const destTmp = path.join(parentDir, `.fo-core-pub-tmp-${pubId}.tmp`);
  const metaTmp = path.join(parentDir, `.fo-core-pub-tmp-${pubId}.meta.json`);
  const lockTmp = path.join(parentDir, `.fo-core-pub-tmp-${pubId}.lock`);
  let destTmpCreated = false;
  let lockFd: number | null = null;

  try {
    // Acquire flock and write ownership metadata before copying
    try {
      lockFd = openSync(lockTmp, constants.O_RDWR | constants.O_CREAT, 0o600);
      tryAcquireFlock(lockFd);
      writeFileSync(
        metaTmp,
        JSON.stringify({
          version: 1,
          subsystem: "backup-core",
          pubId,
          pid: process.pid,
          targetPath: resolvedDest,
          createdAt: Date.now(),
        }),
        { mode: 0o600 },
      );
    } catch {
      /* best effort */
    }

    try {
      copyFileFn(sourceFile, destTmp, constants.COPYFILE_EXCL);
      destTmpCreated = true;
      try {
        chmodSync(destTmp, 0o600);
      } catch {
        /* best effort */
      }
    } catch (copyErr: unknown) {
      throw new BackupCoreError(
        `Failed to stage backup file on destination filesystem: ${(copyErr as Error).message}`,
        "IO_ERROR",
        copyErr,
      );
    }

    try {
      syncFileFn(destTmp);
    } catch (syncErr) {
      throw new BackupCoreError(
        `Failed to synchronize staged backup file: ${(syncErr as Error).message}`,
        "IO_ERROR",
        syncErr,
      );
    }

    // Verify staged copy size matches source before publishing
    const srcSize = lstatSync(sourceFile).size;
    const tmpSize = lstatSync(destTmp).size;
    if (srcSize !== tmpSize) {
      throw new BackupCoreError(
        `Staged backup file size mismatch: expected ${srcSize} bytes, found ${tmpSize}`,
        "IO_ERROR",
      );
    }

    // Hash the staged copy using bounded-memory streaming SHA-256 and compare with expected source digest
    const destHash = computeFileSha256Sync(destTmp);
    if (destHash.bytes !== srcSize) {
      throw new BackupCoreError(
        `Staged backup file byte count mismatch: expected ${srcSize} bytes, streamed ${destHash.bytes}`,
        "IO_ERROR",
      );
    }

    if (options.expectedSha256) {
      const srcHash = computeFileSha256Sync(sourceFile);
      if (srcHash.sha256 !== options.expectedSha256) {
        throw new BackupCoreError(
          `Source file was modified concurrently during staging: expected ${options.expectedSha256}, got ${srcHash.sha256}`,
          "IO_ERROR",
        );
      }
      if (destHash.sha256 !== options.expectedSha256) {
        throw new BackupCoreError(
          `Staged backup file integrity mismatch: expected digest ${options.expectedSha256}, got ${destHash.sha256}`,
          "IO_ERROR",
        );
      }
    } else {
      const srcHash = computeFileSha256Sync(sourceFile);
      if (destHash.sha256 !== srcHash.sha256) {
        throw new BackupCoreError(
          `Staged backup file integrity mismatch: content digest differs from source (${destHash.sha256} vs ${srcHash.sha256})`,
          "IO_ERROR",
        );
      }
    }

    // Try hardlink on destination filesystem (succeeds if EXDEV was the only issue previously)
    let published = false;
    try {
      linkFn(destTmp, resolvedDest);
      published = true;
      try {
        unlinkFn(destTmp);
      } catch {
        /* best effort */
      }
    } catch (secondLinkErr: unknown) {
      const code = (secondLinkErr as { code?: string })?.code;
      if (code === "EEXIST" || pathExistsOrSymlink(resolvedDest)) {
        throw new BackupCoreError(
          `Destination path already exists: ${resolvedDest}`,
          "TARGET_EXISTS",
        );
      }
    }

    if (!published) {
      // Use Darwin atomic no-replace primitive
      const renamex = getDarwinRenamex();
      if (!renamex) {
        throw new BackupCoreError(
          `Atomic exclusive file publication is unsupported on filesystem at '${parentDir}' without native no-replace primitives (link failed: ${linkErrCode ?? "unknown"}).`,
          "UNSUPPORTED_FILESYSTEM",
        );
      }

      const errno = renamex(destTmp, resolvedDest);
      if (errno === 0) {
        published = true;
        destTmpCreated = false;
      } else if (errno === 17 /* EEXIST */) {
        throw new BackupCoreError(
          `Destination path already exists: ${resolvedDest}`,
          "TARGET_EXISTS",
        );
      } else if (errno === 45 /* ENOTSUP / EOPNOTSUPP */ || errno === 1 /* EPERM */) {
        throw new BackupCoreError(
          `Filesystem at '${parentDir}' does not support atomic exclusive publication (errno ${errno}).`,
          "UNSUPPORTED_FILESYSTEM",
        );
      } else {
        throw new BackupCoreError(
          `Atomic exclusive file publication failed with errno ${errno}`,
          "IO_ERROR",
        );
      }
    }

    try {
      unlinkFn(sourceFile);
    } catch {
      /* best effort */
    }

    try {
      syncDirFn(parentDir);
    } catch (syncErr) {
      throw new BackupCoreError(
        `Publication succeeded at destination but directory synchronization failed: ${(syncErr as Error).message}`,
        "IO_ERROR",
        syncErr,
      );
    }
  } finally {
    if (lockFd !== null) {
      try {
        releaseFlock(lockFd);
        closeSync(lockFd);
      } catch {
        /* ignore */
      }
    }
    if (pathExistsOrSymlink(lockTmp)) {
      try {
        unlinkSync(lockTmp);
      } catch {
        /* ignore */
      }
    }
    if (pathExistsOrSymlink(metaTmp)) {
      try {
        unlinkSync(metaTmp);
      } catch {
        /* ignore */
      }
    }
    if (pathExistsOrSymlink(destTmp)) {
      try {
        unlinkFn(destTmp);
      } catch {
        /* best effort */
      }
    }
  }
}

/** Check if a path exists, including dangling symlinks that existsSync() misses. */
export function pathExistsOrSymlink(filePath: string): boolean {
  try {
    lstatSync(filePath);
    return true;
  } catch {
    return false;
  }
}

export const PUB_TEMP_FILE_SCAN_RE = /^\.fo-core-pub-tmp-([0-9a-fA-F\-]+)\.(meta\.json|tmp|lock)$/;

export interface PublicationTempCleanupResult {
  cleaned: string[];
  preserved: Array<{ path: string; reason: string }>;
  errors: string[];
}

export function recoverStalePublicationTempFiles(directory: string): PublicationTempCleanupResult {
  const result: PublicationTempCleanupResult = {
    cleaned: [],
    preserved: [],
    errors: [],
  };

  const resolved = path.resolve(directory);
  if (!pathExistsOrSymlink(resolved)) {
    return result;
  }

  let entries: string[];
  try {
    const st = lstatSync(resolved);
    if (st.isSymbolicLink() || !st.isDirectory()) {
      result.errors.push(`Directory is not a regular directory: ${resolved}`);
      return result;
    }
    entries = readdirSync(resolved);
  } catch (err) {
    result.errors.push(`Failed to read directory ${resolved}: ${(err as Error).message}`);
    return result;
  }

  const pubIds = new Set<string>();
  for (const entry of entries) {
    const match = PUB_TEMP_FILE_SCAN_RE.exec(entry);
    if (match && match[1]) {
      pubIds.add(match[1]);
    }
  }

  for (const pubId of pubIds) {
    const metaPath = path.join(resolved, `.fo-core-pub-tmp-${pubId}.meta.json`);
    const tmpPath = path.join(resolved, `.fo-core-pub-tmp-${pubId}.tmp`);
    const lockPath = path.join(resolved, `.fo-core-pub-tmp-${pubId}.lock`);

    const hasMeta = pathExistsOrSymlink(metaPath);
    const hasTmp = pathExistsOrSymlink(tmpPath);
    const hasLock = pathExistsOrSymlink(lockPath);

    if (!hasMeta) {
      // Incomplete multi-file temporary set missing ownership metadata: cannot determine owner, fail closed
      if (hasTmp) result.preserved.push({ path: tmpPath, reason: "MISSING_METADATA" });
      if (hasLock) result.preserved.push({ path: lockPath, reason: "MISSING_METADATA" });
      continue;
    }

    let metaContent: unknown;
    try {
      metaContent = JSON.parse(readFileSync(metaPath, "utf8"));
    } catch {
      result.preserved.push({ path: metaPath, reason: "MALFORMED_METADATA" });
      if (hasTmp) result.preserved.push({ path: tmpPath, reason: "MALFORMED_METADATA" });
      if (hasLock) result.preserved.push({ path: lockPath, reason: "MALFORMED_METADATA" });
      continue;
    }

    const meta = metaContent as Record<string, unknown>;
    if (
      !meta ||
      typeof meta !== "object" ||
      (meta.version !== undefined && meta.version !== 1) ||
      meta.subsystem !== "backup-core" ||
      (meta.pubId !== undefined && meta.pubId !== pubId) ||
      typeof meta.pid !== "number"
    ) {
      result.preserved.push({ path: metaPath, reason: "INVALID_METADATA" });
      if (hasTmp) result.preserved.push({ path: tmpPath, reason: "INVALID_METADATA" });
      if (hasLock) result.preserved.push({ path: lockPath, reason: "INVALID_METADATA" });
      continue;
    }

    if (typeof meta.targetPath === "string") {
      const resolvedTarget = path.resolve(meta.targetPath);
      if (path.dirname(resolvedTarget) !== resolved || path.relative(resolved, resolvedTarget).includes("..")) {
        result.preserved.push({ path: metaPath, reason: "CANONICAL_PATH_CONTAINMENT_VIOLATION" });
        if (hasTmp) result.preserved.push({ path: tmpPath, reason: "CANONICAL_PATH_CONTAINMENT_VIOLATION" });
        if (hasLock) result.preserved.push({ path: lockPath, reason: "CANONICAL_PATH_CONTAINMENT_VIOLATION" });
        continue;
      }
    }

    let lockFd: number | null = null;
    let lockAcquired = false;
    try {
      if (hasLock) {
        lockFd = openSync(lockPath, constants.O_RDWR, 0o600);
        lockAcquired = tryAcquireFlock(lockFd);
      } else {
        lockAcquired = true;
      }
    } catch {
      lockAcquired = false;
    }

    try {
      if (!lockAcquired) {
        result.preserved.push({ path: metaPath, reason: "ACTIVE_LOCK_HELD" });
        if (hasTmp) result.preserved.push({ path: tmpPath, reason: "ACTIVE_LOCK_HELD" });
        if (hasLock) result.preserved.push({ path: lockPath, reason: "ACTIVE_LOCK_HELD" });
        continue;
      }

      if (isPidAlive(meta.pid as number)) {
        result.preserved.push({ path: metaPath, reason: "PID_ALIVE" });
        if (hasTmp) result.preserved.push({ path: tmpPath, reason: "PID_ALIVE" });
        if (hasLock) result.preserved.push({ path: lockPath, reason: "PID_ALIVE" });
        continue;
      }

      // Safe to delete abandoned publication temp files
      try {
        if (pathExistsOrSymlink(tmpPath)) {
          unlinkSync(tmpPath);
          result.cleaned.push(tmpPath);
        }
        if (pathExistsOrSymlink(metaPath)) {
          unlinkSync(metaPath);
          result.cleaned.push(metaPath);
        }
        if (pathExistsOrSymlink(lockPath)) {
          unlinkSync(lockPath);
          result.cleaned.push(lockPath);
        }
      } catch (rmErr) {
        result.errors.push(`Failed to clean publication temp files for ${pubId}: ${(rmErr as Error).message}`);
      }
    } finally {
      if (lockFd !== null) {
        try {
          releaseFlock(lockFd);
          closeSync(lockFd);
        } catch {
          /* ignore */
        }
      }
    }
  }

  return result;
}

/**
 * Scan a directory and safely clean up manager-owned incomplete temporary backup staging directories
 * and stale publication temp files. Does not touch regular files, active operations, or artifacts owned by other subsystems.
 */
export function cleanupOrphanTemporaryFiles(directory: string): { cleaned: string[]; errors: string[] } {
  const stagingResult = cleanSubsystemStaging(directory, "backup-core", CORE_STAGING_SCAN_RE);
  const pubTempResult = recoverStalePublicationTempFiles(directory);
  return {
    cleaned: [...stagingResult.cleaned, ...pubTempResult.cleaned],
    errors: [...stagingResult.errors, ...pubTempResult.errors],
  };
}

export function computeFileSha256(filePath: string): Promise<string> {
  const resolved = path.resolve(filePath);
  let st: ReturnType<typeof lstatSync>;
  try {
    st = lstatSync(resolved);
  } catch (err) {
    return Promise.reject(
      new BackupCoreError(
        `Failed to stat ${resolved}: ${(err as Error).message}`,
        "IO_ERROR",
        err,
      ),
    );
  }
  if (st.isSymbolicLink()) {
    return Promise.reject(
      new BackupCoreError(
        `Cannot compute checksum: path is a symbolic link: ${resolved}`,
        "INVALID_PATH",
      ),
    );
  }
  if (!st.isFile()) {
    return Promise.reject(
      new BackupCoreError(
        `Cannot compute checksum: path is not a regular file: ${resolved}`,
        "INVALID_PATH",
      ),
    );
  }

  return new Promise<string>((resolve, reject) => {
    const hash = createHash("sha256");
    const stream = createReadStream(resolved);
    stream.on("data", (chunk) => hash.update(chunk));
    stream.on("end", () => resolve(hash.digest("hex")));
    stream.on("error", (err) =>
      reject(
        new BackupCoreError(
          `Failed to compute backup checksum: ${err.message}`,
          "IO_ERROR",
          err,
        ),
      ),
    );
  });
}

/**
 * Synchronously computes SHA-256 digest and verified byte count of a file using bounded chunks (64 KiB),
 * never buffering whole multi-gigabyte files into memory.
 */
export function computeFileSha256Sync(
  filePath: string,
  bufferSize = 64 * 1024,
): { sha256: string; bytes: number } {
  const resolved = path.resolve(filePath);
  let st: ReturnType<typeof lstatSync>;
  try {
    st = lstatSync(resolved);
  } catch (err) {
    throw new BackupCoreError(
      `Failed to stat ${resolved}: ${(err as Error).message}`,
      "IO_ERROR",
      err,
    );
  }
  if (st.isSymbolicLink()) {
    throw new BackupCoreError(
      `Cannot compute checksum: path is a symbolic link: ${resolved}`,
      "INVALID_PATH",
    );
  }
  if (!st.isFile()) {
    throw new BackupCoreError(
      `Cannot compute checksum: path is not a regular file: ${resolved}`,
      "INVALID_PATH",
    );
  }

  let fd: number;
  try {
    fd = openSync(resolved, constants.O_RDONLY);
  } catch (err) {
    throw new BackupCoreError(
      `Failed to open file for checksum computation: ${(err as Error).message}`,
      "IO_ERROR",
      err,
    );
  }

  try {
    const hash = createHash("sha256");
    const buf = Buffer.alloc(bufferSize);
    let totalBytes = 0;
    while (true) {
      let bytesRead = 0;
      try {
        bytesRead = readSync(fd, buf, 0, buf.length, null);
      } catch (readErr) {
        throw new BackupCoreError(
          `Failed while streaming checksum from file: ${(readErr as Error).message}`,
          "IO_ERROR",
          readErr,
        );
      }
      if (bytesRead === 0) break;
      hash.update(buf.subarray(0, bytesRead));
      totalBytes += bytesRead;
    }
    return { sha256: hash.digest("hex"), bytes: totalBytes };
  } finally {
    try {
      closeSync(fd);
    } catch {
      /* ignore */
    }
  }
}

export interface SqlitePathCheckResult {
  isSame: boolean;
  isAuxiliary: boolean;
  auxiliaryType?: string;
  sourceCanonical: string;
  destCanonical: string;
}

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Robustly inspect whether destPath matches sourceDbPath or an SQLite auxiliary file
 * (WAL, SHM, journal, statement journal, master journal).
 * Handles canonical realpaths, parent canonicalization for pending paths, symlinks,
 * and case insensitivity on Darwin / Windows without relying on crude prefix comparisons.
 */
export function isSqliteAuxiliaryOrSamePath(
  sourceDbPath: string,
  destPath: string,
): SqlitePathCheckResult {
  let sourceCanonical = path.resolve(sourceDbPath);
  try {
    sourceCanonical = realpathSync(sourceCanonical);
  } catch {
    try {
      const parentCan = realpathSync(path.dirname(sourceCanonical));
      sourceCanonical = path.join(parentCan, path.basename(sourceCanonical));
    } catch {
      /* keep resolved */
    }
  }

  let destCanonical = path.resolve(destPath);
  try {
    destCanonical = realpathSync(destCanonical);
  } catch {
    try {
      const parentCan = realpathSync(path.dirname(destCanonical));
      destCanonical = path.join(parentCan, path.basename(destCanonical));
    } catch {
      /* keep resolved */
    }
  }

  // Also inspect symlink target if destPath is a symlink (including dangling symlinks)
  let destLinkTargetCanonical: string | null = null;
  try {
    const l = lstatSync(destPath);
    if (l.isSymbolicLink()) {
      const target = readlinkSync(destPath);
      const absTarget = path.resolve(path.dirname(destPath), target);
      try {
        destLinkTargetCanonical = realpathSync(absTarget);
      } catch {
        try {
          const parentCan = realpathSync(path.dirname(absTarget));
          destLinkTargetCanonical = path.join(parentCan, path.basename(absTarget));
        } catch {
          destLinkTargetCanonical = absTarget;
        }
      }
    }
  } catch {
    /* destPath does not exist */
  }

  const checkPair = (src: string, dst: string): { isSame: boolean; isAuxiliary: boolean; auxiliaryType?: string } => {
    const isDarwinOrWin = process.platform === "darwin" || process.platform === "win32";
    const srcDir = path.dirname(src);
    const dstDir = path.dirname(dst);
    const sameDir = isDarwinOrWin
      ? srcDir.toLowerCase() === dstDir.toLowerCase()
      : srcDir === dstDir;

    if (!sameDir) {
      return { isSame: false, isAuxiliary: false };
    }

    const sBase = path.basename(src);
    const dBase = path.basename(dst);
    const sLower = isDarwinOrWin ? sBase.toLowerCase() : sBase;
    const dLower = isDarwinOrWin ? dBase.toLowerCase() : dBase;

    if (sLower === dLower) {
      return { isSame: true, isAuxiliary: false };
    }

    // SQLite auxiliary file suffixes for database base S:
    // S-wal
    // S-shm
    // S-journal (or S-journal\d+)
    // S-mj[0-9a-fA-F]+ (master journal)
    const auxRegex = new RegExp(
      `^${escapeRegex(sLower)}-(wal|shm|journal(?:\\d+)?|mj[0-9a-fA-F]+)$`,
      isDarwinOrWin ? "i" : "",
    );
    const match = auxRegex.exec(dLower);
    if (match) {
      return { isSame: false, isAuxiliary: true, auxiliaryType: match[1] };
    }

    return { isSame: false, isAuxiliary: false };
  };

  const primary = checkPair(sourceCanonical, destCanonical);
  if (primary.isSame || primary.isAuxiliary) {
    return {
      ...primary,
      sourceCanonical,
      destCanonical,
    };
  }

  if (destLinkTargetCanonical) {
    const linkCheck = checkPair(sourceCanonical, destLinkTargetCanonical);
    if (linkCheck.isSame || linkCheck.isAuxiliary) {
      return {
        ...linkCheck,
        sourceCanonical,
        destCanonical: destLinkTargetCanonical,
      };
    }
  }

  return {
    isSame: false,
    isAuxiliary: false,
    sourceCanonical,
    destCanonical,
  };
}

function validateDestination(
  destinationPath: string,
  sourceDbFilename: string | undefined,
  createDirectory: boolean,
): { resolvedDest: string; parentDir: string } {
  if (
    typeof destinationPath !== "string" ||
    !destinationPath.trim() ||
    destinationPath.includes("\0")
  ) {
    throw new BackupCoreError(
      "Invalid destination path: path must be a non-empty string without null bytes.",
      "INVALID_PATH",
    );
  }

  if (destinationPath.endsWith(path.sep) || destinationPath.endsWith("/")) {
    throw new BackupCoreError(
      `Destination path must be a file, not a directory: ${destinationPath}`,
      "INVALID_PATH",
    );
  }

  const resolvedDest = path.resolve(destinationPath);

  // Guard against backing up onto the active database file itself or its auxiliary files
  if (
    sourceDbFilename &&
    sourceDbFilename !== ":memory:" &&
    sourceDbFilename !== ""
  ) {
    const check = isSqliteAuxiliaryOrSamePath(sourceDbFilename, resolvedDest);
    if (check.isSame) {
      throw new BackupCoreError(
        `Destination path cannot be the same as the source database: ${resolvedDest}`,
        "SAME_AS_SOURCE",
      );
    }
    if (check.isAuxiliary) {
      throw new BackupCoreError(
        `Destination path cannot target an SQLite auxiliary file of the source database (${check.auxiliaryType}): ${resolvedDest}`,
        "SQLITE_AUXILIARY_FILE",
      );
    }
  }

  if (pathExistsOrSymlink(resolvedDest)) {
    try {
      const stat = statSync(resolvedDest);
      if (stat.isDirectory()) {
        throw new BackupCoreError(
          `Destination path already exists and is a directory: ${resolvedDest}`,
          "INVALID_PATH",
        );
      }
    } catch (err) {
      if (err instanceof BackupCoreError) throw err;
      // Dangling symlink
    }
    throw new BackupCoreError(
      `Destination path already exists: ${resolvedDest}`,
      "TARGET_EXISTS",
    );
  }

  const parentDir = path.dirname(resolvedDest);
  if (!pathExistsOrSymlink(parentDir)) {
    if (createDirectory) {
      try {
        mkdirSync(parentDir, { recursive: true, mode: 0o700 });
        try {
          chmodSync(parentDir, 0o700);
        } catch {
          /* best effort */
        }
      } catch (err) {
        throw new BackupCoreError(
          `Failed to create backup directory ${parentDir}: ${(err as Error).message}`,
          "IO_ERROR",
          err,
        );
      }
    } else {
      throw new BackupCoreError(
        `Parent directory does not exist: ${parentDir}`,
        "DIRECTORY_NOT_FOUND",
      );
    }
  } else {
    const parentStat = lstatSync(parentDir);
    if (parentStat.isSymbolicLink()) {
      throw new BackupCoreError(
        `Destination parent directory cannot be a symbolic link: ${parentDir}`,
        "INVALID_PATH",
      );
    }
    if (!parentStat.isDirectory()) {
      throw new BackupCoreError(
        `Parent path is not a directory: ${parentDir}`,
        "INVALID_PATH",
      );
    }
  }

  return { resolvedDest, parentDir };
}

export class BackupCore {
  constructor(
    private readonly db: Database,
    private readonly defaultOptions: BackupCoreOptions = {},
  ) {}

  /**
   * Create a consistent, verified online SQLite backup at `destinationPath`.
   */
  async createBackup(
    destinationPath: string,
    options: BackupOptions = {},
  ): Promise<BackupResult> {
    const startedAt = performance.now();
    const now = options.now ?? this.defaultOptions.now ?? Date.now;
    const createDir =
      options.createDirectory ?? this.defaultOptions.createDirectory ?? false;

    const { resolvedDest, parentDir } = validateDestination(
      destinationPath,
      this.db.filename,
      createDir,
    );

    const operationId = randomUUID();
    const stagingDirName = `.${path.basename(resolvedDest)}.fo-core.${operationId}.tmp`;
    const stagingDir = path.join(parentDir, stagingDirName);

    // Create private 0o700 staging directory exclusively (non-recursive)
    try {
      mkdirSync(stagingDir, { mode: 0o700 });
    } catch (err) {
      throw new BackupCoreError(
        `Failed to create staging directory ${stagingDir}: ${(err as Error).message}`,
        "IO_ERROR",
        err,
      );
    }

    let stagingSucceeded = false;
    let published = false;
    let fallbackCreatedDest = false;
    let lockFd: number | null = null;

    try {
      try {
        chmodSync(stagingDir, 0o700);
      } catch (chmodErr) {
        throw new BackupCoreError(
          `Failed to set private permissions on staging directory ${stagingDir}: ${(chmodErr as Error).message}`,
          "IO_ERROR",
          chmodErr,
        );
      }

      // Establish advisory flock for active operation tracking
      const lockPath = path.join(stagingDir, STAGING_LOCK_FILENAME);
      try {
        lockFd = openSync(lockPath, constants.O_RDWR | constants.O_CREAT, 0o600);
        tryAcquireFlock(lockFd);
      } catch {
        /* best effort lock */
      }

      // Record initial ownership metadata
      const metadata: StagingOwnershipMetadata = {
        version: 1,
        subsystem: "backup-core",
        operationId,
        runnerOperationId: options.runnerOperationId,
        pid: process.pid,
        createdAt: now(),
        state: "preparing",
        targetPath: resolvedDest,
      };
      writeStagingOwnershipMetadata(stagingDir, metadata, false);

      await options.beforeVacuum?.(stagingDir);

      // Phase 1: SQLite online snapshot
      metadata.state = "writing";
      writeStagingOwnershipMetadata(stagingDir, metadata, false);

      const tempDbPath = path.join(stagingDir, "backup.sqlite");

      // Yield to event loop so pending I/O and timers run before synchronous SQLite snapshot
      await new Promise((resolve) => setImmediate(resolve));

      const disposeLag = beginLagLabel("sqlite online backup");
      // Set umask to 0o077 only if running inside isolated child process, to avoid modifying process-wide umask in main process
      const isIsolated = process.env.FORGEORBIT_ISOLATED_OPERATION === "1";
      const prevUmask = isIsolated ? process.umask(0o077) : null;
      try {
        this.db.run("VACUUM INTO ?", [tempDbPath]);
      } catch (err) {
        metadata.state = "failed";
        writeStagingOwnershipMetadata(stagingDir, metadata, false);
        throw new BackupCoreError(
          `SQLite VACUUM INTO failed: ${(err as Error).message}`,
          "SQLITE_ERROR",
          err,
        );
      } finally {
        if (prevUmask !== null) {
          process.umask(prevUmask);
        }
        disposeLag();
      }

      // Restrictive permissions on temporary snapshot
      try {
        chmodSync(tempDbPath, 0o600);
      } catch {
        /* best effort */
      }

      // Durability: flush snapshot bytes and staging directory entries
      const syncFileFn = options.fs?.syncFile ?? this.defaultOptions.fs?.syncFile ?? syncFile;
      const syncDirFn = options.fs?.syncDirectory ?? this.defaultOptions.fs?.syncDirectory ?? syncDirectory;

      try {
        syncFileFn(tempDbPath);
        syncDirFn(stagingDir);
      } catch (syncErr) {
        metadata.state = "failed";
        writeStagingOwnershipMetadata(stagingDir, metadata, false);
        throw new BackupCoreError(
          `Failed to synchronize staging database: ${(syncErr as Error).message}`,
          "IO_ERROR",
          syncErr,
        );
      }

      // Optional test hook before verification
      await options.afterVacuum?.(tempDbPath);

      // Phase 2: Integrity Verification & Checksum
      metadata.state = "verifying";
      writeStagingOwnershipMetadata(stagingDir, metadata, false);

      const integrity = BackupCore.verifyIntegrity(tempDbPath);
      if (!integrity.ok) {
        metadata.state = "failed";
        writeStagingOwnershipMetadata(stagingDir, metadata, false);
        throw new BackupCoreError(
          `Backup verification failed: ${integrity.issues.join("; ")}`,
          "VERIFICATION_FAILED",
        );
      }

      // Calculate checksum BEFORE publication to prevent post-publication checksum failures
      const sha256 = await computeFileSha256(tempDbPath);
      const stat = statSync(tempDbPath);

      // Optional test hook before atomic publish
      await options.afterVerify?.(tempDbPath);

      // Phase 3: Publication
      metadata.state = "publishing";
      writeStagingOwnershipMetadata(stagingDir, metadata, false);

      published = false;
      publishFileExclusive(tempDbPath, resolvedDest, {
        fs: {
          link: options.fs?.link ?? this.defaultOptions.fs?.link,
          copyFile: options.fs?.copyFile ?? this.defaultOptions.fs?.copyFile,
          unlink: options.fs?.unlink ?? this.defaultOptions.fs?.unlink,
        },
        syncFileFn,
        syncDirFn,
        expectedSha256: sha256,
      });
      published = true;

      let publicationReceipt: PublicationReceiptWriteOutcome | undefined;
      if (options.runnerOperationId) {
        // The artifact is durably published here. A receipt failure is recorded
        // as a structured evidence gap; it never un-publishes the backup and is
        // never silently discarded.
        publicationReceipt = writeBackupPublicationReceipt({
          operationId: options.runnerOperationId,
          targetPath: resolvedDest,
          sha256,
          bytes: stat.size,
          pid: process.pid,
          publishedAt: now(),
        });
      }

      // Ensure restrictive permissions on published backup
      try {
        chmodSync(resolvedDest, 0o600);
      } catch {
        /* best effort */
      }

      // Synchronize parent directory so publication directory entry is durable
      try {
        syncDirFn(parentDir);
      } catch (syncErr) {
        throw new BackupCoreError(
          `Failed to synchronize backup directory: ${(syncErr as Error).message}`,
          "IO_ERROR",
          syncErr,
        );
      }

      metadata.state = "completed";
      writeStagingOwnershipMetadata(stagingDir, metadata, false);
      stagingSucceeded = true;

      await options.afterPublish?.(resolvedDest);

      const durationMs = Math.round(performance.now() - startedAt);

      return {
        path: resolvedDest,
        bytes: stat.size,
        durationMs,
        sha256,
        createdAt: now(),
        publicationReceipt,
      };
    } finally {
      if (lockFd !== null) {
        releaseFlock(lockFd);
        try {
          closeSync(lockFd);
        } catch {
          /* ignore */
        }
      }
      // Always remove private staging directory
      try {
        if (existsSync(stagingDir)) {
          rmSync(stagingDir, { recursive: true, force: true });
        }
      } catch {
        /* best effort cleanup */
      }
      if (!published && fallbackCreatedDest && pathExistsOrSymlink(resolvedDest)) {
        try {
          unlinkSync(resolvedDest);
        } catch {
          /* best effort cleanup */
        }
      }
    }
  }

  /**
   * Verify the integrity of an existing SQLite database file independently.
   */
  verifyIntegrity(filePath: string): IntegrityCheckResult {
    return BackupCore.verifyIntegrity(filePath);
  }

  /**
   * Static helper to independently open and run PRAGMA integrity_check on a database file.
   */
  static verifyIntegrity(filePath: string): IntegrityCheckResult {
    const resolved = path.resolve(filePath);
    if (!pathExistsOrSymlink(resolved)) {
      return { ok: false, issues: [`File not found: ${resolved}`] };
    }
    let st: ReturnType<typeof lstatSync>;
    try {
      st = lstatSync(resolved);
    } catch (err) {
      return { ok: false, issues: [`Failed to stat ${resolved}: ${(err as Error).message}`] };
    }
    if (st.isSymbolicLink()) {
      return { ok: false, issues: [`Database path cannot be a symbolic link: ${resolved}`] };
    }
    if (st.isDirectory()) {
      return { ok: false, issues: [`Path is a directory: ${resolved}`] };
    }
    if (!st.isFile()) {
      return { ok: false, issues: [`Database path is not a regular file (special file / FIFO): ${resolved}`] };
    }

    let verifyDb: Database | null = null;
    try {
      verifyDb = new Database(resolved, { readonly: true });
      const rows = verifyDb
        .query<{ integrity_check: string }, []>("PRAGMA integrity_check;")
        .all();
      const integrityOk = rows.length === 1 && rows[0]?.integrity_check === "ok";
      const issues: string[] = [];
      if (!integrityOk) {
        const integrityIssues = rows.map((r) => r.integrity_check).filter(Boolean);
        issues.push(...(integrityIssues.length ? integrityIssues : ["Unknown integrity check failure"]));
      }

      // Foreign key validation (FO-P2-003-R2A: P2-8)
      interface ForeignKeyCheckRow {
        table: string;
        rowid: number;
        parent: string;
        fkid: number;
      }
      let fkRows: ForeignKeyCheckRow[] = [];
      try {
        fkRows = verifyDb
          .query<ForeignKeyCheckRow, []>("PRAGMA foreign_key_check;")
          .all();
      } catch (fkErr) {
        issues.push(`PRAGMA foreign_key_check failed: ${(fkErr as Error).message}`);
      }

      if (fkRows.length > 0) {
        for (const fk of fkRows) {
          issues.push(
            `Foreign key violation in table '${fk.table}' (rowid: ${fk.rowid}) referencing parent table '${fk.parent}' (fkid: ${fk.fkid})`,
          );
        }
        return {
          ok: false,
          issues,
          foreignKeyViolations: fkRows.map((fk) => ({
            table: fk.table,
            rowid: Number(fk.rowid),
            parent: fk.parent,
            fkid: Number(fk.fkid),
          })),
        };
      }

      if (issues.length > 0) {
        return { ok: false, issues };
      }

      return { ok: true, issues: [] };
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      return { ok: false, issues: [message] };
    } finally {
      if (verifyDb) {
        try {
          verifyDb.close();
        } catch {
          /* ignore close error */
        }
      }
    }
  }
}

