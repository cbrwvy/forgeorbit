/**
 * SQLite online backup core (FO-P2-001).
 *
 * Provides safe, point-in-time snapshots of an active SQLite database without
 * requiring application shutdown or exclusive write locks.
 *
 * ## Mechanism & Guarantees
 *
 * 1. Uses SQLite's native `VACUUM INTO ?` statement with parameterized binding.
 *    In WAL mode (`PRAGMA journal_mode = WAL;`), `VACUUM INTO` reads committed
 *    data from both the main `.sqlite` file and active WAL frames, producing a
 *    clean, defragmented, self-contained single-file database.
 * 2. Writes output to a temporary sibling file (`.<target>.<uuid>.tmp`) within the
 *    destination directory to ensure atomic publishing via `renameSync` on the
 *    same filesystem.
 * 3. Never overwrites an existing valid backup file.
 * 4. Independently opens the generated temporary database in read-only mode and
 *    executes `PRAGMA integrity_check;` before publication.
 * 5. Automatically cleans up incomplete temporary files if any step fails.
 * 6. Enforces restrictive permissions (`0o600` on files, `0o700` on directories).
 * 7. Measures wall-clock duration and computes streaming SHA-256 digest without
 *    high memory overhead.
 * 8. Brackets the synchronous SQLite snapshot operation with `beginLagLabel` so
 *    any event-loop stall is attributed cleanly in the lag monitor.
 *
 * ## Event-Loop & Concurrency Notes
 *
 * NOTE: While `createBackup` is an async method returning a Promise, Bun SQLite's
 * `VACUUM INTO ?` and `PRAGMA integrity_check` execute synchronously on Bun's main
 * thread. SQLite snapshot generation will block the event loop for the duration of
 * page copying. We yield cooperatively before vacuuming via `setImmediate` and
 * bracket the vacuum with `beginLagLabel`, but callers must be aware that very large
 * databases will stall other event-loop tasks while SQLite performs disk I/O.
 */

